"""Keep Markdown links on the site where the target is published.

A relative link is resolved from the file it was written in: the page's own
location, or for a page generated by ``repo_pages`` the original repository
file. A target that is a ``docs/`` page or a published repository file stays
a relative link to that page; any other repository file or directory becomes
a GitHub URL at the configured revision.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from urllib.parse import quote, unquote

from sphinx.application import Sphinx

from repo_pages import GENERATED_ROOTS, published_pages

_LINK_RE = re.compile(
    r"(?P<prefix>!?\[[^\]]*\]\()"
    r"(?P<target><[^>]+>|[^)\s]+)"
    r"(?P<suffix>(?:\s+[\"'][^\"']*[\"'])?\))"
)


def _is_generated(path: Path, docs_dir: Path) -> bool:
    try:
        relative = path.relative_to(docs_dir)
    except ValueError:
        return False
    return relative.parts[0] in GENERATED_ROOTS


def _rewrite_repository_links(app: Sphinx, docname: str, source: list[str]) -> None:
    page_path = Path(app.env.doc2path(docname, base=True)).resolve()
    docs_dir = Path(app.srcdir).resolve()
    repository_root = docs_dir.parent
    repository = os.environ.get("OPENPFC_REPOSITORY", "VTT-ProperTune/OpenPFC")
    revision = os.environ.get("OPENPFC_REVISION", "master")
    pages = published_pages(repository_root)
    origins = {doc: src for src, doc in pages.items()}
    written_in = origins.get(docname, page_path)

    def replace(match: re.Match[str]) -> str:
        raw_target = match.group("target")
        bracketed = raw_target.startswith("<") and raw_target.endswith(">")
        target = raw_target[1:-1] if bracketed else raw_target

        if target.startswith(("#", "/", "mailto:", "http://", "https://")):
            return match.group(0)

        path_part, separator, fragment = target.partition("#")
        resolved = (written_in.parent / unquote(path_part)).resolve()
        if resolved.is_dir() and (resolved / "README.md").resolve() in pages:
            resolved = (resolved / "README.md").resolve()

        # docs/README.md is the repository's guide index; the handbook front
        # page is its published form.
        if resolved == docs_dir / "README.md":
            resolved = docs_dir / "index.md"

        page = None
        if resolved in pages:
            page = docs_dir / f"{pages[resolved]}.md"
        elif not _is_generated(resolved, docs_dir):
            try:
                resolved.relative_to(docs_dir)
                page = resolved
            except ValueError:
                pass

        if page is not None:
            if page == resolved and written_in == page_path:
                return match.group(0)
            url = quote(os.path.relpath(page, page_path.parent).replace(os.sep, "/"), safe="/.-_")
        else:
            try:
                relative = resolved.relative_to(repository_root)
            except ValueError:
                return match.group(0)
            if not resolved.exists():
                return match.group(0)
            kind = "tree" if resolved.is_dir() else "blob"
            url = (
                f"https://github.com/{repository}/{kind}/{revision}/"
                f"{quote(relative.as_posix(), safe='/')}"
            )

        if separator:
            url = f"{url}#{fragment}"
        if bracketed:
            url = f"<{url}>"
        return f"{match.group('prefix')}{url}{match.group('suffix')}"

    source[0] = _LINK_RE.sub(replace, source[0])


def setup(app: Sphinx) -> dict[str, object]:
    app.setup_extension("repo_pages")
    app.connect("source-read", _rewrite_repository_links)
    return {
        "version": "1.1",
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
