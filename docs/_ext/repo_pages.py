"""Publish repository guides that live outside docs/ as handbook pages.

The repository files stay the only source. At build time each one is copied
into the Sphinx source tree under a stable docname (``INSTALL.md`` becomes
``project/install``, ``apps/tungsten/README.md`` becomes
``apps/tungsten/index``). The generated directories are ignored by git.
``repo_links`` resolves the links of a generated page from the file's
original location, so links between published files stay on the site.
"""

from __future__ import annotations

import functools
from pathlib import Path

from sphinx.application import Sphinx

# Single files: repository path -> docname.
PROJECT_PAGES = {
    "INSTALL.md": "project/install",
    "CHANGELOG.md": "project/changelog",
    "CONTRIBUTING.md": "project/contributing",
    "easybuild/README.md": "project/easybuild",
    "containers/runtime/README.md": "project/containers",
}

# Every README below these directories becomes the index page of its
# directory under the same path. Other notes there (measurement records,
# derivations) stay repository files and are linked on GitHub.
MIRRORED_TREES = ("apps", "examples")

GENERATED_ROOTS = ("project", *MIRRORED_TREES)

_NOTICE = "<!-- Generated from {source} by docs/_ext/repo_pages.py. Edit {source}. -->\n\n"


def _readmes(repository_root: Path, tree: str) -> list[Path]:
    return sorted(p for p in (repository_root / tree).rglob("README.md") if "build" not in p.parts)


@functools.lru_cache(maxsize=4)
def published_pages(repository_root: Path) -> dict[Path, str]:
    """Map each published repository file (resolved path) to its docname."""
    pages = {(repository_root / src).resolve(): doc for src, doc in PROJECT_PAGES.items()}
    for tree in MIRRORED_TREES:
        for path in _readmes(repository_root, tree):
            relative = path.relative_to(repository_root).parent / "index"
            pages[path.resolve()] = relative.as_posix()
    return {path: doc for path, doc in pages.items() if path.exists()}


def _generate(app: Sphinx) -> None:
    docs_dir = Path(app.srcdir).resolve()
    repository_root = docs_dir.parent
    for root in GENERATED_ROOTS:
        generated = docs_dir / root
        if generated.exists() and not (generated / ".generated").exists():
            raise RuntimeError(f"{generated} exists and was not generated by repo_pages")
    pages = published_pages(repository_root)
    for source, docname in pages.items():
        target = docs_dir / f"{docname}.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        relative_source = source.relative_to(repository_root).as_posix()
        text = _NOTICE.format(source=relative_source) + source.read_text(encoding="utf-8")
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
    current = {docs_dir / f"{docname}.md" for docname in pages.values()}
    for root in GENERATED_ROOTS:
        for stale in (docs_dir / root).rglob("*.md") if (docs_dir / root).exists() else ():
            if stale not in current:
                stale.unlink()
        for directory in sorted((docs_dir / root).rglob("*"), reverse=True) if (docs_dir / root).exists() else ():
            if directory.is_dir() and not any(directory.iterdir()):
                directory.rmdir()
    for root in GENERATED_ROOTS:
        marker = docs_dir / root / ".generated"
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.write_text("Generated by docs/_ext/repo_pages.py; safe to delete.\n", encoding="utf-8")


def setup(app: Sphinx) -> dict[str, object]:
    app.connect("builder-inited", _generate)
    return {
        "version": "1.0",
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
