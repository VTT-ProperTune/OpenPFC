"""Stage the Quarto lessons into openpfc-pages, without running numerical code.

The source checkout determines the OpenPFC revision. Render the destination
with `quarto render --profile examples`; Quarto merges the lesson inputs
into the website project and applies its native openpfc-html format.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]


def stage(site: Path) -> None:
    if not (site / "_quarto.yml").is_file():
        raise ValueError(f"Not a Quarto website: {site}")
    destination = site / "learn"
    marker = destination / ".openpfc-examples"
    if destination.exists():
        if not marker.is_file():
            raise ValueError(f"Refusing to replace an unowned directory: {destination}")
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    marker.write_text("Generated by OpenPFC scripts/stage_example_book.py\n")

    source = ROOT / "examples"
    files = {source / "index.qmd", source / "coverage.qmd", source / "coverage.json",
             source / "_metadata.yml", source / "styles.css", source / "references.bib"}
    for chapter in sorted(source.glob("*/*/index.qmd")):
        files.add(chapter)
        files.update(chapter.parent.glob("*.cpp"))
        files.update(chapter.parent.glob("*.json"))
        files.update(chapter.parent.glob("*.toml"))
        for suffix in ("*.hpp", "*.h"):
            files.update(chapter.parent.glob(suffix))
            files.update(chapter.parent.parent.glob(suffix))
    files.update(source.glob("*/figures/*.svg"))
    files.update(source.glob("*/*/figures/*.svg"))
    for path in sorted(files):
        target = destination / path.relative_to(source)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)

    extension = site / "_extensions/openpfc-include-code-files"
    if extension.exists():
        shutil.rmtree(extension)
    shutil.copytree(source / "_extensions/include-code-files", extension)
    # Use a namespaced filter so an unrelated site extension cannot be replaced.
    metadata = destination / "_metadata.yml"
    metadata.write_text(metadata.read_text().replace("- include-code-files", "- openpfc-include-code-files"))

    profile = site / "_quarto-examples.yml"
    notice = "# Generated by OpenPFC scripts/stage_example_book.py\n"
    if profile.exists() and not profile.read_text().startswith(notice):
        raise ValueError(f"Refusing to replace an unowned profile: {profile}")
    profile.write_text(notice + """project:
  render:
    - learn/index.qmd
    - learn/coverage.qmd
    - learn/*/*/index.qmd
  resources:
    - learn/**/*.cpp
    - learn/**/*.hpp
    - learn/**/*.h
    - learn/**/*.json
    - learn/**/*.toml
execute:
  enabled: false
""")
    print(f"Staged OpenPFC lessons in {destination}; render with --profile examples")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("site", type=Path, help="openpfc-pages checkout or disposable preview")
    args = parser.parse_args()
    stage(args.site.resolve())


if __name__ == "__main__":
    main()
