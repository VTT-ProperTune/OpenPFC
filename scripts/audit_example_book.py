"""Reconcile the lesson inventory with executable declarations and chapter metadata.

--sync updates mappings and the rendered progress page. A mapping records a
chapter's declared scope, not proof that its mathematics or capabilities pass.
Pending examples and book programs remain visible until actually converted.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def array(front_matter: str, name: str) -> list[str]:
    match = re.search(r"^" + re.escape(name) + r":\s*\[([^\]]*)\]", front_matter, re.M)
    if not match:
        return []
    return [value.strip().strip("\"'") for value in next(csv.reader([match[1]])) if value.strip()]


def inventory(source: Path) -> tuple[list[dict], dict[int, str]]:
    targets = {}
    for cmake in sorted(source.rglob("CMakeLists.txt")):
        # This repository declares literal executable names and source paths.
        text = "\n".join(line.split("#", 1)[0] for line in cmake.read_text().splitlines())
        for name, filename in re.findall(r"add_executable\s*\(\s*(\S+)\s+([^\s)]+)", text, re.I):
            if name.startswith("test_"):
                continue
            if "$" in name or "$" in filename:
                raise ValueError(f"Resolve generated executable declaration in {cmake}: {name}")
            path = cmake.parent / filename
            if not path.is_file():
                raise ValueError(f"Missing executable source: {path}")
            if name in targets:
                raise ValueError(f"Duplicate executable: {name}")
            targets[name] = {"target": name, "source": path.relative_to(source).as_posix(),
                             "chapter": None, "capabilities": []}
    programs = {}
    for chapter in sorted(source.glob("*/*/index.qmd")):
        metadata = chapter.read_text().split("---", 2)[1]
        relative = chapter.relative_to(source).as_posix()
        declared = array(metadata, "targets")
        if not declared:
            raise ValueError(f"Chapter must identify a runnable target: {chapter}")
        for name in declared:
            if name not in targets:
                raise ValueError(f"Unknown chapter target {name}: {chapter}")
            if targets[name]["chapter"]:
                raise ValueError(f"Target has multiple chapters: {name}")
            targets[name]["chapter"] = relative
            targets[name]["capabilities"] = array(metadata, "capabilities")
        for value in array(metadata, "book-programs"):
            number = int(value)
            if number not in range(1, 41) or number in programs:
                raise ValueError(f"Invalid or duplicate book program {number}: {chapter}")
            programs[number] = relative
    return [targets[name] for name in sorted(targets)], programs


def progress_page(data: dict) -> str:
    chapters = sorted({row["chapter"] for row in data["examples"] if row["chapter"]})
    mapped = sum(row["chapter"] is not None for row in data["book"])
    text = f'''---
title: "The example collection: coverage and next steps"
description: "An explicit inventory of existing programs, teaching chapters and all forty book programs."
---

<!-- SPDX-FileCopyrightText: 2026 VTT Technical Research Centre of Finland Ltd -->
<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->
<!-- Generated by scripts/audit_example_book.py --sync; edit coverage.json scope notes. -->

::: {{.article-body}}
::: {{.article-title}}
[OpenPFC / A growing collection]{{.lesson-kicker}}

# The example collection: coverage and next steps

[Follow what is taught, what is adapted, and what still needs a chapter.]{{.lesson-deck}}
:::

There are {len(data['examples'])} declared runnable example targets and
{len(chapters)} Quarto teaching chapters. The table includes older programs
that have not yet been converted. Target counts exclude test executables;
optional configurations can affect which targets a particular build enables.

## Spectral Methods in MATLAB

The [author's collection](https://people.maths.ox.ac.uk/trefethen/spectral.html)
contains forty programs. Currently {mapped} have a corresponding lesson.
A link means that the lesson declares coverage of that experiment; the
scope column states changes in method or presentation. It does not mean
an unmodified MATLAB program was translated line for line. Pending rows
remain in the inventory while applicability and implementation are assessed.

| Program | Experiment | Lesson and scope |
|---:|---|---|
'''
    for row in data["book"]:
        chapter = row["chapter"]
        scope = row["scope"].replace("|", "\\|")
        label = f"[Read the lesson]({chapter}). {scope}" if chapter else "Pending assessment and implementation."
        title = row["title"].replace("|", "\\|")
        text += f"| [{row['program']}]({row['source']}) | {title} | {label} |\n"
    text += "\n## Existing runnable examples\n\n| Target | Teaching chapter |\n|---|---|\n"
    for row in data["examples"]:
        link = f"[Read the lesson]({row['chapter']})" if row["chapter"] else "Pending conversion."
        text += f"| `{row['target']}` | {link} |\n"
    text += "\n## Additional sources\n\n"
    for row in data["additional_sources"]:
        link = f"[Read the lesson]({row['chapter']})" if row["chapter"] else "Pending conversion."
        text += f"- `{row['source']}`: {link}\n"
    text += '''
## Capability coverage

The machine-readable [coverage inventory](coverage.json) also tracks capability families.
These links identify focused introductory lessons, not complete API coverage:
a heat propagator does not demonstrate every exponential integrator, and a
fixed-step restart does not establish an adaptive restart contract.

| Capability family | Current teaching chapters |
|---|---|
'''
    for family in data["capability_families"]:
        links = ", ".join(f"[{Path(chapter).parent.name}]({chapter})" for chapter in family["chapters"])
        text += f"| {family['name']} | {links or 'Pending a teaching chapter.'} |\n"
    text += "\nEvery family needs an actual model, a useful mathematical story and appropriate runtime evidence.\n\n[Return to the lessons](index.qmd).\n:::\n"
    return text


def audit(source: Path, sync: bool = False) -> tuple[int, int, int]:
    manifest = source / "coverage.json"
    original = manifest.read_text()
    data = json.loads(original)
    targets, programs = inventory(source)
    if {row["program"] for row in data["book"]} != set(range(1, 41)):
        raise ValueError("The inventory must retain all forty book programs")
    data["examples"] = targets
    chapters = {row["chapter"] for row in targets if row["chapter"]}
    for family in data["capability_families"]:
        if not set(family["chapters"]).issubset(chapters):
            raise ValueError(f"Unknown chapter in capability family {family['name']}")
    for row in data["book"]:
        row["chapter"] = programs.get(row["program"])
        if row["chapter"] and row["scope"] == "unassessed":
            raise ValueError(f"Describe the actual method/scope of book program {row['program']}")
    for row in data["additional_sources"]:
        if not (source / row["source"]).is_file():
            raise ValueError(f"Missing additional source {row['source']}")
    rendered = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    page = progress_page(data)
    destination = source / "coverage.qmd"
    if sync:
        manifest.write_text(rendered)
        destination.write_text(page)
    elif original != rendered or not destination.is_file() or destination.read_text() != page:
        raise ValueError("Example inventory is stale; run scripts/audit_example_book.py --sync")
    return len(targets), len({row["chapter"] for row in targets if row["chapter"]}), len(programs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sync", action="store_true")
    args = parser.parse_args()
    try:
        targets, chapters, programs = audit(ROOT / "examples", args.sync)
    except (ValueError, KeyError) as error:
        raise SystemExit(str(error)) from error
    print(f"Inventory consistent: {targets} targets, {chapters} chapters, {programs}/40 book mappings. "
          "Unconverted examples and unassessed programs remain explicit.")


if __name__ == "__main__":
    main()
